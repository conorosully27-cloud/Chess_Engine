// Game phase: 24 with all pieces on the board, 0 with only kings and pawns.
inline constexpr int PHASE_WEIGHT[6] = {0, 1, 1, 2, 4, 0};
inline constexpr int MAX_PHASE = 24;

// Material plus table value of each piece on each square, signed: positive
// for White, negative for Black, so a position's total is a plain sum.
struct Table {
  int mg[PIECE_NB][64];
  int eg[PIECE_NB][64];
};

constexpr Table make_table() {
  Table t{};
  for (int c = 0; c < 2; c++)
    for (int pt = 0; pt < 6; pt++)
      for (int s = 0; s < 64; s++) {
        const int idx = c == WHITE ? (7 - (s >> 3)) * 8 + (s & 7) : s;
        const int sign = c == WHITE ? 1 : -1;
        t.mg[c * 6 + pt][s] = sign * (MATERIAL_MG[pt] + PST_MG[pt][idx]);
        t.eg[c * 6 + pt][s] = sign * (MATERIAL_EG[pt] + PST_EG[pt][idx]);
      }
  return t;
}

inline constexpr Table PSQ = make_table();

